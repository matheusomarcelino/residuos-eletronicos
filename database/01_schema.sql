SET client_min_messages = warning;

DROP VIEW  IF EXISTS v_total_por_tipo, v_solicitacoes_detalhe;
DROP TABLE IF EXISTS item_descartado, solicitacao_descarte, ponto_tipo,
                     ponto_coleta, tipo_residuo, usuario, unidade CASCADE;
DROP FUNCTION IF EXISTS fn_validar_fluxo_status(), fn_atualizado_em(), fn_validar_tipo_do_ponto();

-- ---------- UNIDADE: loja franqueada ou setor da sede ----------
CREATE TABLE unidade (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(120) NOT NULL UNIQUE,
    tipo    VARCHAR(10)  NOT NULL DEFAULT 'loja'
            CONSTRAINT ck_unidade_tipo CHECK (tipo IN ('loja', 'setor')),
    cidade  VARCHAR(80)  NOT NULL DEFAULT ''
);

-- ---------- USUARIO: só nome, e-mail e unidade (RNF04 / LGPD) ----------
CREATE TABLE usuario (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(150) NOT NULL,
    email       VARCHAR(254) NOT NULL UNIQUE
                CONSTRAINT ck_usuario_email CHECK (email = lower(email) AND email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    senha_hash  VARCHAR(128) NOT NULL,           -- nunca a senha em texto (RNF03)
    unidade_id  INTEGER REFERENCES unidade (id) ON DELETE SET NULL,
    perfil      VARCHAR(15)  NOT NULL DEFAULT 'colaborador'
                CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('colaborador', 'administrador')),
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------- TIPO_RESIDUO ----------
CREATE TABLE tipo_residuo (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(80) NOT NULL UNIQUE,
    orientacoes  TEXT        NOT NULL DEFAULT ''
);

-- ---------- PONTO_COLETA ----------
CREATE TABLE ponto_coleta (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    endereco  VARCHAR(200) NOT NULL,
    horario   VARCHAR(120) NOT NULL DEFAULT '',
    ativo     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_ponto_nome_endereco UNIQUE (nome, endereco)
);

-- ---------- PONTO_TIPO: relação N:N "aceita" (chave composta) ----------
CREATE TABLE ponto_tipo (
    ponto_id  INTEGER NOT NULL REFERENCES ponto_coleta (id) ON DELETE CASCADE,
    tipo_id   INTEGER NOT NULL REFERENCES tipo_residuo (id) ON DELETE CASCADE,
    PRIMARY KEY (ponto_id, tipo_id)
);

-- ---------- SOLICITACAO_DESCARTE ----------
CREATE TABLE solicitacao_descarte (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          INTEGER NOT NULL REFERENCES usuario (id)      ON DELETE RESTRICT,
    unidade_id          INTEGER NOT NULL REFERENCES unidade (id)      ON DELETE RESTRICT,
    ponto_id            INTEGER NOT NULL REFERENCES ponto_coleta (id) ON DELETE RESTRICT,
    data                DATE    NOT NULL DEFAULT CURRENT_DATE
                        CONSTRAINT ck_solic_data CHECK (data <= CURRENT_DATE),
    status              VARCHAR(12) NOT NULL DEFAULT 'solicitado'
                        CONSTRAINT ck_solic_status CHECK (status IN ('solicitado', 'coletado', 'encaminhado')),
    atualizado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_por_id   INTEGER REFERENCES usuario (id) ON DELETE SET NULL
);
-- unidade_id repete a unidade do usuário de propósito: guarda a unidade NO MOMENTO da
-- solicitação, mesmo que o usuário mude de unidade depois (não é redundância acidental).

-- ---------- ITEM_DESCARTADO ----------
CREATE TABLE item_descartado (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id  INTEGER NOT NULL REFERENCES solicitacao_descarte (id) ON DELETE CASCADE,
    tipo_id         INTEGER NOT NULL REFERENCES tipo_residuo (id)         ON DELETE RESTRICT,
    quantidade      INTEGER NOT NULL DEFAULT 1
                    CONSTRAINT ck_item_quantidade CHECK (quantidade >= 1),
    observacao      VARCHAR(200) NOT NULL DEFAULT ''
);

-- ---------- Índices nas chaves estrangeiras e nos filtros mais usados ----------
CREATE INDEX ix_usuario_unidade   ON usuario (unidade_id);
CREATE INDEX ix_solic_usuario     ON solicitacao_descarte (usuario_id);
CREATE INDEX ix_solic_unidade     ON solicitacao_descarte (unidade_id);
CREATE INDEX ix_solic_ponto       ON solicitacao_descarte (ponto_id);
CREATE INDEX ix_solic_status_data ON solicitacao_descarte (status, data DESC);
CREATE INDEX ix_item_solicitacao  ON item_descartado (solicitacao_id);
CREATE INDEX ix_item_tipo         ON item_descartado (tipo_id);
CREATE INDEX ix_ponto_tipo_tipo   ON ponto_tipo (tipo_id);

-- =====================================================================
-- GATILHOS: regras de negócio garantidas pelo banco
-- =====================================================================

-- Regra 1 (RF04): a solicitação nasce "solicitado" e só avança solicitado -> coletado -> encaminhado.
CREATE FUNCTION fn_validar_fluxo_status() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'solicitado' THEN
            RAISE EXCEPTION 'Toda solicitação deve ser criada com status "solicitado" (recebido: %).', NEW.status
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF NEW.status <> OLD.status THEN
        IF NOT ((OLD.status = 'solicitado' AND NEW.status = 'coletado')
             OR (OLD.status = 'coletado'   AND NEW.status = 'encaminhado')) THEN
            RAISE EXCEPTION 'Transição de status inválida: % -> %.', OLD.status, NEW.status
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_solic_fluxo_status
    BEFORE INSERT OR UPDATE OF status ON solicitacao_descarte
    FOR EACH ROW EXECUTE FUNCTION fn_validar_fluxo_status();

-- Regra 2: registra o momento de qualquer alteração.
CREATE FUNCTION fn_atualizado_em() RETURNS trigger AS $$
BEGIN
    NEW.atualizado_em := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_solic_atualizado_em
    BEFORE UPDATE ON solicitacao_descarte
    FOR EACH ROW EXECUTE FUNCTION fn_atualizado_em();

-- Regra 3 (RF02/RF05): o ponto só recebe os tipos cadastrados para ele
-- (ponto sem nenhum tipo cadastrado aceita qualquer tipo, como no sistema web).
CREATE FUNCTION fn_validar_tipo_do_ponto() RETURNS trigger AS $$
DECLARE
    v_ponto INTEGER;
BEGIN
    SELECT ponto_id INTO v_ponto FROM solicitacao_descarte WHERE id = NEW.solicitacao_id;
    IF EXISTS (SELECT 1 FROM ponto_tipo WHERE ponto_id = v_ponto)
       AND NOT EXISTS (SELECT 1 FROM ponto_tipo WHERE ponto_id = v_ponto AND tipo_id = NEW.tipo_id) THEN
        RAISE EXCEPTION 'O ponto de coleta % não aceita o tipo de resíduo %.', v_ponto, NEW.tipo_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_item_tipo_do_ponto
    BEFORE INSERT OR UPDATE OF tipo_id, solicitacao_id ON item_descartado
    FOR EACH ROW EXECUTE FUNCTION fn_validar_tipo_do_ponto();

-- =====================================================================
-- VISÕES
-- =====================================================================
CREATE VIEW v_solicitacoes_detalhe AS
SELECT s.id,
       s.data,
       s.status,
       u.nome        AS usuario,
       un.nome       AS unidade,
       p.nome        AS ponto,
       COALESCE(SUM(i.quantidade), 0) AS total_itens
FROM solicitacao_descarte s
JOIN usuario       u  ON u.id  = s.usuario_id
JOIN unidade       un ON un.id = s.unidade_id
JOIN ponto_coleta  p  ON p.id  = s.ponto_id
LEFT JOIN item_descartado i ON i.solicitacao_id = s.id
GROUP BY s.id, u.nome, un.nome, p.nome;

CREATE VIEW v_total_por_tipo AS
SELECT t.nome AS tipo,
       COALESCE(SUM(i.quantidade), 0) AS total,
       ROUND(100.0 * COALESCE(SUM(i.quantidade), 0)
             / NULLIF(SUM(SUM(i.quantidade)) OVER (), 0), 1) AS percentual
FROM tipo_residuo t
LEFT JOIN item_descartado i ON i.tipo_id = t.id
GROUP BY t.id, t.nome;
